#!/usr/bin/env bash
# Generate the checked-in PGO profile from the canonical root benchmark suite.
#
# Usage:
#   scripts/bench/pgo.sh
#   PGO_BENCHTIME=1000x scripts/bench/pgo.sh
#
# The profile is intentionally produced from package "." benchmarks: those are
# the public recipe workloads that exercise the root planner/runtime stack with
# deterministic goavtest codecs and containers.
set -euo pipefail

cd "$(dirname "$0")/../.."

profile="${PGO_PROFILE:-default.pgo}"
meta="${PGO_META:-default.pgo.meta}"
bench_re="${PGO_BENCH_REGEX:-Benchmark(RecordPackets|RemuxPackets|DecodeToFrameSink|DecodeEncode|Resample|Resize|BranchFanout|SharedMuxGroup|Mix|Composite|SelectPassthrough)}"
benchtime="${PGO_BENCHTIME:-100x}"
count="${PGO_COUNT:-1}"
pkg="${PGO_PACKAGE:-.}"

tmp="$(mktemp "${profile}.tmp.XXXXXX")"
cleanup() {
  rm -f "$tmp"
}
trap cleanup EXIT

CGO_ENABLED="${CGO_ENABLED:-0}" go test -pgo=off -run '^$' -bench "$bench_re" -benchmem -benchtime "$benchtime" -count "$count" -cpuprofile "$tmp" "$pkg" >/dev/null
mv "$tmp" "$profile"

bench_hash="$(shasum -a 256 bench_test.go | awk '{print $1}')"
script_hash="$(shasum -a 256 scripts/bench/pgo.sh | awk '{print $1}')"
generated_at="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
go_version="$(go version)"

cat > "$meta" <<EOF
# Generated by scripts/bench/pgo.sh; refresh when bench_test.go or this script changes.
version=1
package=$pkg
bench_regex=$bench_re
benchtime=$benchtime
count=$count
bench_test_sha256=$bench_hash
pgo_script_sha256=$script_hash
generated_at=$generated_at
go_version=$go_version
EOF

echo "wrote $profile"
echo "wrote $meta"
